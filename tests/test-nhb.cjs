'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const sandbox={self:{},Float64Array,Float32Array,Array,Number,Math};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('modulationscope/nhb-filterbank.js','utf8'),sandbox,{filename:'nhb-filterbank.js'});
vm.runInContext(fs.readFileSync('modulationscope/nhb-core.js','utf8'),sandbox,{filename:'nhb-core.js'});
const bank=sandbox.self.NHB_FILTERBANK;
assert.equal(bank.filters.length,129);
assert.equal(bank.centerHz.length,128);
assert(bank.centerHz.every((x,i)=>i===0 || x>bank.centerHz[i-1]));
assert(bank.filters.every(f=>f.a.length===f.b.length && f.a[0]===1));
const engine=new sandbox.self.NHBAuditory(16000,bank);
const chunk=new Float32Array(4096);
for(let k=0;k<chunk.length;k++)chunk[k]=.02*Math.sin(2*Math.PI*440*k/16000);
for(let i=0;i<3;i++)engine.add(chunk);
const r=engine.snapshot(10,151);
assert.equal(r.ys.length,128);assert.equal(r.xs.length,151);assert.equal(r.map.length,128);
assert.equal(r.map[0].length,151);
const finite=r.map.flat().filter(Number.isFinite);
assert(finite.length>0);
assert(finite.every(v=>v>=0));
assert(finite.some(v=>v>1e-12));
assert(r.map.every(row=>Number.isNaN(row[0])), 'Unrecorded time must stay NaN');
assert(engine.framesSeen>180&&engine.framesSeen<200);
console.log('NHB 2021 bank / streaming spectrogram PASS: '+engine.framesSeen+' frames; 128 bands; '+finite.length+' pixels');
